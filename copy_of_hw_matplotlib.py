import matplotlib.pyplot as plt
import numpy as np

"""### Part 1a - Shear Diagram

You will create your shear diagram in the code block below.

"""

# Defined variables for the simply supported beam
L = 6.0         # Full length of the beam (ft)
R_A = 170.0     # Pin support reaction force (lb)
R_B = 410.0     # Roller support reaction force (lb)
P_1 = 100.0     # Point load at x = 2 ft (lb)
q_1 = 120.0     # Distributed load from x = 0 to 2 ft (lb/ft)
q_2 = 120.0     # Distributed load from x = 4 to 6 ft (lb/ft)

# Create x array
x = np.linspace(0, L, 500)
V = np.zeros_like(x)

# Loop over x to calculate piecewise shear function
for i, xi in enumerate(x):
    if xi < 2:
        V[i] = R_A - (q_1 * xi)
    elif 2 <= xi < 4:
        V[i] = R_A - (q_1 * 2) - P_1
    else:  # xi >= 4
        V[i] = R_A - (q_1 * 2) - P_1 + R_B - (q_2 * (xi - 4))

# Plotting the Shear Diagram
plt.figure(figsize=(10, 4))
plt.plot(x, V, color='green', linewidth=2, label='Shear (V)')
plt.fill_between(x, V, color='green', alpha=0.3)
plt.title('Shear Diagram for Simply Supported Beam')
plt.xlabel('Position along beam, x (ft)')
plt.ylabel('Internal Shear, V (lb)')
plt.axhline(0, color='black', linewidth=1, linestyle='--')
plt.grid(True, linestyle=':', alpha=0.7)
plt.legend()
plt.show()

"""### Part 1b - Moment Diagram

You will create your moment diagram in the code block below.
"""

# Defined variables (copied from Part 1a)
L = 6.0
R_A = 170.0
R_B = 410.0
P_1 = 100.0
q_1 = 120.0
q_2 = 120.0

# Create x array
x = np.linspace(0, L, 500)
M = np.zeros_like(x)

# Loop over x to calculate piecewise moment function
for i, xi in enumerate(x):
    if xi < 2:
        M[i] = (R_A * xi) - (q_1 * xi**2 / 2)
    elif 2 <= xi < 4:
        M[i] = (R_A * xi) - (q_1 * 2 * (xi - 1)) - (P_1 * (xi - 2))
    else:  # xi >= 4
        M[i] = (R_A * xi) - (q_1 * 2 * (xi - 1)) - (P_1 * (xi - 2)) + \
               (R_B * (xi - 4)) - (q_2 * (xi - 4) * (xi - 4) / 2)

# Plotting the Moment Diagram
plt.figure(figsize=(10, 4))
plt.plot(x, M, color='red', linewidth=2, label='Moment (M)')
plt.fill_between(x, M, color='red', alpha=0.3)
plt.title('Bending Moment Diagram for Simply Supported Beam')
plt.xlabel('Position along beam, x (ft)')
plt.ylabel('Internal Moment, M (lb-ft)')
plt.axhline(0, color='black', linewidth=1, linestyle='--')
plt.grid(True, linestyle=':', alpha=0.7)
plt.legend()
plt.show()

